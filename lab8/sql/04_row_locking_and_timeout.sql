-- ============================================================================
-- СЕАНС А · Крок 1: Накладання ексклюзивного блокування рядка (FOR UPDATE)
-- ============================================================================
BEGIN;

SELECT *
FROM lab08.readings
WHERE id = 2
FOR UPDATE;

-- Залишити транзакцію відкритою! Замок ExclusiveLock утримується на рядку id = 2.


-- ============================================================================
-- СЕАНС Б · Крок 2: Спроба зміни із сесійним запобіжником lock_timeout
-- ============================================================================
-- Встановлюємо таймаут очікування блокування 3 секунди
SET lock_timeout = '3s';

-- Запит переходить у режим очікування і через 3 секунди переривається:
-- ERROR: canceling statement due to lock timeout (SQLSTATE 55P03)
UPDATE lab08.readings
SET temperature = 26.0
WHERE id = 2;


-- ============================================================================
-- СЕАНС А · Крок 3: Звільнення блокування
-- ============================================================================
COMMIT;


-- ============================================================================
-- СЕАНС Б · Крок 4: Повторення модифікації після зняття замка
-- ============================================================================
UPDATE lab08.readings
SET temperature = 26.0
WHERE id = 2;

-- Скидання таймауту до системного замовчування
RESET lock_timeout;

-- Перевірка успішного оновлення
SELECT * FROM lab08.readings WHERE id = 2;


-- ============================================================================
-- МОНІТОРИНГ БЛОКУВАНЬ: Перевірка системного каталогу pg_locks
-- ============================================================================
SELECT
    locktype,
    relation::regclass,
    mode,
    granted,
    pid
FROM pg_locks
WHERE relation = 'lab08.readings'::regclass;
