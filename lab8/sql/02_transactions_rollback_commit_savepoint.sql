-- Файл: 02_transactions_rollback_commit_savepoint.sql
-- Призначення: Завдання 1. Підтвердження (COMMIT), скасування (ROLLBACK) та SAVEPOINT
-- ============================================================================

-- ============================================================================
-- 1. Приклад 1.1: Скасування змін транзакції (ROLLBACK)
-- Зміна температури запису 1 з 20.0 до 30.0 °C із подальшим відкатом
-- ============================================================================
BEGIN;

UPDATE lab08.readings
SET temperature = 30.0
WHERE id = 1;

-- Всередині транзакції бачимо модифіковане значення (30.0 °C)
SELECT id, sensor_id, temperature
FROM lab08.readings
WHERE id = 1;

-- Скасування всіх дій транзакції
ROLLBACK;

-- Перевірка повернення попереднього значення (20.0 °C)
SELECT id, sensor_id, temperature
FROM lab08.readings
WHERE id = 1;


-- ============================================================================
-- 2. Приклад 1.2: Підтвердження змін транзакції (COMMIT)
-- Зміна температури запису 1 до 25.0 °C із персистентною фіксацією
-- ============================================================================
BEGIN;

UPDATE lab08.readings
SET temperature = 25.0
WHERE id = 1;

-- Остаточна фіксація у WAL та базі даних
COMMIT;

-- Перевірка зафіксованого результату (25.0 °C)
SELECT id, sensor_id, temperature
FROM lab08.readings
WHERE id = 1;


-- ============================================================================
-- 3. Точки збереження транзакції (SAVEPOINT та частковий відкат)
-- ============================================================================
BEGIN;

-- Крок 1: Валідне оновлення першого запису
UPDATE lab08.readings SET temperature = 27.5 WHERE id = 1;

-- Створення іменованої точки збереження
SAVEPOINT sp_step1;

-- Крок 2: Помилкове оновлення другого запису
UPDATE lab08.readings SET temperature = 99.9 WHERE id = 2;

-- Крок 3: Відкат помилкової операції до точки збереження
ROLLBACK TO SAVEPOINT sp_step1;

-- Фіксація залишкових коректних операцій транзакції
COMMIT;

-- Перевірка: id=1 зберіг 27.5, id=2 залишився 21.0
SELECT id, sensor_id, temperature
FROM lab08.readings
ORDER BY id;
