-- ============================================================================
-- ПІДГОТОВКА: Виконувати у двох незалежних клієнтських терміналах (Сеанс А та Б)
-- ============================================================================

-- У кожному сеансі зафіксуйте унікальний PID бекенду:
SELECT pg_backend_pid();


-- ============================================================================
-- СЕАНС А · Крок 1: Відкриття транзакції та зміна рядка без COMMIT
-- ============================================================================
BEGIN;

UPDATE lab08.readings
SET temperature = 31.0
WHERE id = 1;

-- Сеанс А бачить власні незафіксовані зміни (31.0 °C)
SELECT temperature FROM lab08.readings WHERE id = 1;
-- УВАГА: Не виконувати COMMIT! Залишити транзакцію відкритою.


-- ============================================================================
-- СЕАНС Б · Крок 2: Читання того самого рядка конкурентним клієнтом
-- ============================================================================
-- Сеанс Б не блокується незавершеним UPDATE Сеансу А!
-- Він читає свій узгоджений знімок: попереднє підтверджене значення (25.0 °C)
SELECT temperature FROM lab08.readings WHERE id = 1;


-- ============================================================================
-- СЕАНС А · Крок 3: Фіксація транзакції
-- ============================================================================
COMMIT;


-- ============================================================================
-- СЕАНС Б · Крок 4: Повторне читання після фіксації
-- ============================================================================
-- Новий запит у READ COMMITTED будує новий Snapshot і бачить оновлені 31.0 °C
SELECT temperature FROM lab08.readings WHERE id = 1;


-- ============================================================================
-- ПОГЛИБЛЕНИЙ АНАЛІЗ MVCC: Інспекція системних стовпців заголовка кортежу
-- ============================================================================
-- ctid: фізична адреса (сторінка, зміщення) — зміна з (0,1) на (0,16) доводить створення нового кортежу
-- xmin: ID транзакції-творця
-- xmax: ID транзакції-видаляча (0 = активний «живий» кортеж)
SELECT ctid, xmin, xmax, id, sensor_id, temperature
FROM lab08.readings
WHERE id = 1;
