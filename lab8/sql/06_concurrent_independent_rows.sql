-- Дослідження: чи блокує SELECT ... FOR UPDATE на рядок id = 1 зміну рядка id = 3?

-- ============================================================================
-- СЕАНС А · Крок 1: Початок транзакції та блокування рядка id = 1
-- ============================================================================
BEGIN;

SELECT *
FROM lab08.readings
WHERE id = 1
FOR UPDATE;

-- Залишити відкритим! Кортеж id = 1 монопольно утримується Сеансом А.


-- ============================================================================
-- СЕАНС Б · Крок 2: Спроба зміни іншого запису (id = 3)
-- ============================================================================
-- Операція виконується МИТТЄВО, жодного стану очікування блокування немає!
UPDATE lab08.readings
SET temperature = 28.0
WHERE id = 3;

-- Перевірка зафіксованого результату в Сеансі Б
SELECT * FROM lab08.readings WHERE id = 3;


-- ============================================================================
-- СЕАНС А · Крок 3: Завершення транзакції
-- ============================================================================
COMMIT;


-- ============================================================================
-- ВИСНОВОК:
-- Блокування в PostgreSQL діє на рівні окремих кортежів (Row-Level Locking).
-- Блокування одного рядка не створює взаємних перешкод для обробки інших рядків.
-- ============================================================================
SELECT id, sensor_id, temperature
FROM lab08.readings
ORDER BY id;
