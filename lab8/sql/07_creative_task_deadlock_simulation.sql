-- ============================================================================
-- СЦЕНАРІЙ:
-- Сеанс А захоплює рядок 1 -> намагається захопити рядок 3
-- Сеанс Б захоплює рядок 3 -> намагається захопити рядок 1
-- Виникає циклічна залежність очікування ресурсів (Deadlock)
-- ============================================================================

-- ============================================================================
-- 1. СЕАНС А: Блокування рядка id = 1
-- ============================================================================
BEGIN;

UPDATE lab08.readings
SET temperature = 22.2
WHERE id = 1;


-- ============================================================================
-- 2. СЕАНС Б: Блокування рядка id = 3
-- ============================================================================
BEGIN;

UPDATE lab08.readings
SET temperature = 29.9
WHERE id = 3;


-- ============================================================================
-- 3. СЕАНС А: Спроба змінити рядок id = 3 (переходить у стан очікування)
-- ============================================================================
UPDATE lab08.readings
SET temperature = 23.3
WHERE id = 3;
-- Сеанс А зависає, очікуючи на завершення транзакції Сеансу Б.


-- ============================================================================
-- 4. СЕАНС Б: Спроба змінити рядок id = 1 (замикання циклу дедлоку)
-- ============================================================================
UPDATE lab08.readings
SET temperature = 30.0
WHERE id = 1;

-- РЕЗУЛЬТАТ У СЕАНСІ Б (через інтервал deadlock_timeout = 1s):
-- ERROR: deadlock detected (SQLSTATE 40P01)
-- DETAIL: Process ... waits for ShareLock on transaction ...; blocked by process ...
-- Process ... waits for ShareLock on transaction ...; blocked by process ...


-- ============================================================================
-- 5. ВІДНОВЛЕННЯ ТА ЗВІЛЬНЕННЯ:
-- ============================================================================
-- У Сеансі Б (транзакцію переведено в стан помилки через переривання СУБД):
ROLLBACK;

-- У Сеансі А (автоматично розблокувався після відкату конкурента):
COMMIT;

-- Контрольний стан даних після подолання взаємоблокування:
SELECT id, sensor_id, temperature
FROM lab08.readings
ORDER BY id;
