-- ============================================================================
-- 1. Приклад 4.1: Генерація 100 тестових записів та їх видалення
-- ============================================================================
INSERT INTO lab08.readings (id, sensor_id, temperature)
SELECT id, 1, 20.0
FROM generate_series(100, 199) AS id;

-- Видалення щойно доданих 100 записів (створення dead tuples)
DELETE FROM lab08.readings
WHERE id BETWEEN 100 AND 199;

-- Перевірка логічної кількості рядків (очікувано 3 активні записи)
SELECT count(*) AS total_rows FROM lab08.readings;


-- ============================================================================
-- 2. Приклад 4.2: Аналіз системної статистики накопичення застарілих рядків
-- n_dead_tup відображає наявність 100 невидимих застарілих кортежів
-- ============================================================================
SELECT
    relname,
    n_live_tup,
    n_dead_tup,
    vacuum_count,
    autovacuum_count
FROM pg_stat_user_tables
WHERE schemaname = 'lab08'
  AND relname = 'readings';


-- ============================================================================
-- 3. Приклад 4.3: Ручний запуск очищення та збору статистики
-- УВАГА: Виконувати окремою командою поза транзакційним блоком BEGIN ... COMMIT!
-- ============================================================================
VACUUM (VERBOSE, ANALYZE) lab08.readings;


-- ============================================================================
-- 4. Перевірка результатів очищення у pg_stat_user_tables
-- n_dead_tup скидається в 0, а vacuum_count інкрементується на 1
-- ============================================================================
SELECT
    relname,
    n_live_tup,
    n_dead_tup,
    vacuum_count,
    autovacuum_count
FROM pg_stat_user_tables
WHERE schemaname = 'lab08'
  AND relname = 'readings';
